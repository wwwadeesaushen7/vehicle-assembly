import type {
  PartDefinition,
  VehicleDefinition,
  Category,
  Tool,
  Vec3,
} from "./schema";
function part(
  id: string,
  name: string,
  category: Category,
  shape: string,
  position: Vec3,
  dependsOn: string[],
  tool: Tool,
  fasteners: number,
  mass: number,
  description: string,
  side?: number,
): PartDefinition {
  return {
    id,
    name,
    category,
    shape,
    mount: { position, rotation: 0 },
    dependsOn,
    tool,
    fasteners,
    mass,
    description,
    connector: `fw01:${id}`,
    torqueNm: tool === "torque" ? 110 : tool === "wrench" ? 45 : 5,
    side,
  };
}
